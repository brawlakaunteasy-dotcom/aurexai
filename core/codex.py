# --- the real pipeline --------------------------------------------------------
def _gh(method, url, token, json_body=None, timeout=30):
    return requests.request(
        method, url,
        headers={
            "Authorization": f"Bearer {token}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
        },
        json=json_body, timeout=timeout,
    )


def _log(job, line):
    job.log = (job.log or "") + (line.rstrip() + "\n")
    db.session.commit()


def _run_codex_job(app, job_id, user_id, repo_name):
    """Background worker: AI → real GitHub repo → pushed files."""
    started = time.time()
    with app.app_context():
        job = CodexJob.query.get(job_id)
        user = User.query.get(user_id)
        try:
            token = user.github_token
            if not token:
                job.status = "error"
                _log(job, "GitHub token mavjud emas.")
                return

            # 1) Generate file manifest with AI -------------------------------
            job.status = "generating"
            db.session.commit()
            _log(job, "🤖 AI loyiha rejasini yaratmoqda...")

            codex_model = (AiModel.query.filter_by(is_codex=True, enabled=True).first()
                           or AiModel.query.filter_by(enabled=True, is_codex=False).first())
            if not codex_model:
                job.status = "error"
                _log(job, "Codex modeli sozlanmagan.")
                return

            sys = (
                "Sen Codex'sen — to'liq, ishlovchi loyiha yaratuvchi AI. "
                "Foydalanuvchi topshirig'iga muvofiq, to'liq ishlovchi va sinalgan "
                "loyihani tayyorla. Barcha kerakli fayllar (README.md, requirements/"
                "package.json, asosiy kod, yordamchi modullar) bo'lsin.\n\n"
                "Quyidagi formatda javob ber, boshqa hech narsa qo'shma:\n\n"
                "=== file: <fayl yo'li> ===\n"
                "<fayl mazmuni>\n"
                "=== file: <fayl yo'li> ===\n"
                "<fayl mazmuni>\n\n"
                "Hech qachon markdown code block (``` ``` ) ishlatma — fayl ichidagi "
                "mazmun bevosita yoziladi. Maksimal 25 ta fayl. Har bir fayl o'zining "
                "to'liq mazmuniga ega bo'lsin."
            )
            full_text = []
            res = ai_service.call_chat_stream(
                codex_model,
                [
                    {"role": "system", "content": sys},
                    {"role": "user", "content": job.prompt},
                ],
                on_token=lambda t: full_text.append(t),
                on_status=lambda s: _log(job, f"⏳ {s}"),
                max_retries=4,
            )
            if not res.get("ok"):
                job.status = "error"
                _log(job, f"AI xato: {res.get('error')}")
                return

            files = parse_files_from_ai("".join(full_text))
            _log(job, f"📁 {len(files)} ta fayl tayyor.")

            # 2) Create real GitHub repo --------------------------------------
            job.status = "creating-repo"
            db.session.commit()
            _log(job, f"📦 GitHub'da '{repo_name}' repository yaratilmoqda...")

            r = _gh("POST", f"{GITHUB_API}/user/repos", token, {
                "name": repo_name,
                "description": f"AurexAi Codex: {job.prompt[:140]}",
                "private": False,
                "auto_init": True,
            })
            # If name conflict, append timestamp
            if r.status_code == 422 and "already exists" in r.text.lower():
                repo_name = repo_name + "-" + datetime.utcnow().strftime("%H%M%S")
                _log(job, f"♻ Nom band, qayta urinish: {repo_name}")
                r = _gh("POST", f"{GITHUB_API}/user/repos", token, {
                    "name": repo_name,
                    "description": f"AurexAi Codex: {job.prompt[:140]}",
                    "private": False,
                    "auto_init": True,
                })
            if r.status_code >= 300:
                job.status = "error"
                _log(job, f"GitHub repo yaratishda xato {r.status_code}: {r.text[:300]}")
                return
            repo_data = r.json()
            owner = repo_data["owner"]["login"]
            html_url = repo_data["html_url"]
            job.repo_url = html_url
            db.session.commit()
            _log(job, f"✅ Repo yaratildi: {html_url}")

            # 3) Push each file via Contents API ------------------------------
            job.status = "pushing"
            db.session.commit()

            # Wait briefly for auto-init commit to be available
            time.sleep(2)

            for path, content in files:
                try:
                    encoded = base64.b64encode(content.encode("utf-8")).decode("ascii")
                except Exception as e:
                    _log(job, f"⚠ Fayl encoding xato {path}: {e}")
                    continue

                # Get existing sha (if file exists from auto_init like README.md)
                existing = _gh("GET",
                               f"{GITHUB_API}/repos/{owner}/{repo_name}/contents/{path}",
                               token)
                body = {
                    "message": f"AurexAi Codex: {path}",
                    "content": encoded,
                }
                if existing.status_code == 200:
                    body["sha"] = existing.json().get("sha")

                pr = _gh("PUT",
                         f"{GITHUB_API}/repos/{owner}/{repo_name}/contents/{path}",
                         token, body)
                if pr.status_code >= 300:
                    _log(job, f"⚠ {path} push xato {pr.status_code}: {pr.text[:200]}")
                else:
                    _log(job, f"📤 {path}")

            # 4) Done ---------------------------------------------------------
            job.status = "done"
            elapsed = int(time.time() - started)
            job.seconds_used = elapsed
            add_seconds(user_id, elapsed)
            _log(job, f"🎉 Tayyor! Vaqt: {elapsed}s")
            db.session.commit()

            # Save assistant message into the codex chat
            chat = get_or_create_codex_chat(user)
            summary = (
                f"✅ Loyihangiz tayyor!\n\n"
                f"🔗 {html_url}\n\n"
                f"📁 Fayllar: {len(files)}\n"
                f"⏱ Vaqt: {elapsed}s\n\n"
                f"Repository'ni clone qilib, lokalda ishga tushirsangiz bo'ladi."
            )
            db.session.add(Message(chat_id=chat.id, role="assistant",
                                   content=summary, model=codex_model.model_id))
            db.session.commit()

        except Exception as e:
            try:
                job.status = "error"
                _log(job, f"❌ Kutilmagan xato: {e}")
            except Exception:
                db.session.rollback()
