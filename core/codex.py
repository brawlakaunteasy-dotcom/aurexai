# --- helpers -----------------------------------------------------------------
def get_or_create_codex_chat(user):
    chat = Chat.query.filter_by(user_id=user.id, is_codex=True).first()
    if chat:
        return chat
    chat = Chat(user_id=user.id, title="Codex", is_codex=True, is_locked=True)
    db.session.add(chat)
    db.session.commit()
    return chat


def get_usage(user):
    u = CodexUsage.query.filter_by(user_id=user.id).first()
    if not u:
        u = CodexUsage(user_id=user.id, seconds_used_today=0)
        db.session.add(u)
        db.session.commit()
    u.reset_if_needed()
    db.session.commit()
    return u


def add_seconds(user_id, secs):
    u = CodexUsage.query.filter_by(user_id=user_id).first()
    if not u:
        u = CodexUsage(user_id=user_id, seconds_used_today=0)
        db.session.add(u)
    u.reset_if_needed()
    u.seconds_used_today = (u.seconds_used_today or 0) + int(secs)
    db.session.commit()


def parse_files_from_ai(text):
    """Parse AI output formatted as `=== file: <path> ===\\n<content>`.
    Falls back to a single README.md if no markers detected."""
    pattern = re.compile(r"=== file: (.+?) ===\s*\n(.*?)(?=\n=== file: |\Z)", re.DOTALL)
    files = [(m.group(1).strip(), m.group(2).rstrip()) for m in pattern.finditer(text)]
    if not files:
        files = [("README.md", text.strip() or "# Generated by AurexAi Codex")]
    # de-dup paths and drop empty
    seen = {}
    for p, c in files:
        if p and c is not None:
            seen[p] = c
    return list(seen.items())


def safe_repo_name(name, prompt=""):
    name = (name or prompt).strip()[:60]
    name = re.sub(r"[^a-zA-Z0-9._-]+", "-", name).strip("-").lower()
    if not name:
        name = "aurex-codex-" + datetime.utcnow().strftime("%Y%m%d-%H%M%S")
    return name[:50]


