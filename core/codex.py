"""Codex — REAL GitHub integration.

Pipeline (works end-to-end):
  1. POST /codex/api/github/connect   {token}
     → validates with GitHub /user, persists token+username on user.
  2. POST /codex/api/jobs              {prompt, repo_name?}
     → background worker:
        a. status=generating  — calls codex AiModel to produce file manifest
        b. status=creating-repo — POST /user/repos
        c. status=pushing — PUT each file via Contents API
        d. status=done, repo_url=<html_url>

Daily compute limit (4h) is enforced for PLUS users.

Note: full Codespace auto-debug loop is *not* included; the AI generates
the project, opens a real public repo, and returns the link. From there
the user can run / debug locally or open a Codespace manually.
"""
